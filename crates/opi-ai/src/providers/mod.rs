//! The pinned builtin provider profile table (task 20.34).
//!
//! Source-qualified metadata for every one of the 42 builtin provider
//! factories in the pi 1.3.0 capability inventory: canonical ids, display
//! names, default base URLs, env API-key names, auth schemes, OAuth
//! availability and endpoint semantics. The table is data only —
//! construction lives in [`crate::provider_collection`], which turns these
//! profiles plus the bundled catalog into registered providers over the
//! existing wire adapters. Legacy opi ids (`gemini`, `vertex`, `bedrock`,
//! `openai-responses`) are not aliases here: canonical ids replace them and
//! the coding agent migrates references at its boundary.

use crate::auth::AuthScheme;

/// Endpoint semantics of one builtin profile.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum BuiltinEndpoint {
    /// The provider has one fixed default base URL.
    ProviderBaseUrl,
    /// Catalog entries carry their own base URLs.
    PerModelBaseUrl,
    /// Azure: the endpoint and deployment mapping are configuration-derived.
    AzureDeployment,
    /// Vertex: the base URL is templated on the configured location.
    VertexLocation,
    /// Bedrock: the regional runtime endpoint derives from credentials.
    BedrockRegion,
    /// A dynamic provider whose models/endpoint the catalog store owns.
    Dynamic,
}

/// One builtin provider profile, source-qualified from the pinned factory.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct BuiltinProviderProfile {
    /// Canonical provider id (also the registration id).
    pub id: &'static str,
    /// Display name.
    pub name: &'static str,
    /// Default base URL, when the factory pins one.
    pub base_url: Option<&'static str>,
    /// Environment variable holding the API key, when env-key sourced.
    pub api_key_env: Option<&'static str>,
    /// Wire auth scheme for the env key.
    pub auth_scheme: AuthScheme,
    /// An OAuth flow family exists for this provider.
    pub oauth: bool,
    /// OAuth credentials must not reach this provider's classifiers
    /// (pi `filterAllModels`: ChatGPT tokens only work on Responses).
    pub hides_classifiers_on_oauth: bool,
    /// The provider ships only classifier models (typesafe).
    pub classifier_only: bool,
    /// Non-secret credential label for chain-sourced providers.
    pub credential_label: Option<&'static str>,
    /// Endpoint semantics.
    pub endpoint: BuiltinEndpoint,
}

/// The complete builtin profile table, sorted by canonical id (42 entries).
pub fn builtin_provider_profiles() -> &'static [BuiltinProviderProfile] {
    BUILTIN_PROVIDER_PROFILES
}

/// Look up one profile by canonical id.
pub fn builtin_profile(id: &str) -> Option<&'static BuiltinProviderProfile> {
    BUILTIN_PROVIDER_PROFILES
        .iter()
        .find(|profile| profile.id == id)
}

